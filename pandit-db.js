function getFestivalsForDate(date) {
  const key = date.toISOString().slice(0, 10);
  return FESTIVALS_2026.filter(f => f.date === key);
}
function getUpcomingFestivals(daysAhead = 30) {
  const today = new Date();
  const limit = new Date(today.getTime() + daysAhead * 86400000);
  return FESTIVALS_2026.filter(f => {
    const fd = new Date(f.date);
    return fd >= today && fd <= limit;
  }).sort((a, b) => a.date.localeCompare(b.date));
}

