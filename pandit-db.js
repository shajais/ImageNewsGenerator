function getPanchang(date) {
  // Julian Day Number
  const jd = dateToJD(date);
  // Reference new moon: Jan 6, 2000 at 18:14 UTC → JD 2451551.259
  const refNewMoon = 2451551.259;
  const synodic = 29.530588853;
  const elapsed = jd - refNewMoon;
  const cyclePos = ((elapsed % synodic) + synodic) % synodic;
  // Tithi (1-30 in full cycle; 1-15 shukla, 1-14+amavasya krishna)
  const tithiIndex = Math.floor(cyclePos * 30 / synodic); // 0-29
  const paksha = tithiIndex < 15 ? 'शुक्ल पक्ष' : 'कृष्ण पक्ष';
  const tithiInPaksha = tithiIndex < 15 ? tithiIndex : tithiIndex - 15;
  const tithiName = tithiIndex === 14 ? 'पूर्णिमा' : tithiIndex === 29 ? 'अमावस्या' : TITHIS[Math.min(tithiInPaksha, 13)];
  // Nakshatra (27 in 360°, moon travels ~13.17°/day)
  const moonLon = ((jd - 2451545.0) * 13.176396 + 231.67) % 360;
  const nakIndex = Math.floor(moonLon / (360 / 27));
  // Yoga (27 yogas; sum of sun+moon longitude / 13.33°)
  const sunLon = ((jd - 2451545.0) * 0.9856473 + 280.46) % 360;
  const yogaIndex = Math.floor(((sunLon + moonLon) % 360) / (360 / 27));
  // Varar
  const day = date.getDay(); // 0=Sun
  // Festivals for today
  const festivals = getFestivalsForDate(date);
  return {
    tithi: tithiName,
    paksha,
    nakshatra: NAKSHATRAS[nakIndex % 27],
    yoga: YOGAS[yogaIndex % 27],
    varar: VARARS[day],
    festivals,
    tithiIndex,
    cyclePos: Math.round(cyclePos * 100) / 100
  };
}

function dateToJD(date) {
  const Y = date.getFullYear(), M = date.getMonth() + 1, D = date.getDate();
  const A = Math.floor((14 - M) / 12);
  const y = Y + 4800 - A;
  const m = M + 12 * A - 3;
  return D + Math.floor((153 * m + 2) / 5) + 365 * y
       + Math.floor(y / 4) - Math.floor(y / 100) + Math.floor(y / 400) - 32045;
}

